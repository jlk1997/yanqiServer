  @Get('audits/export')
  async exportAudits(
    @Res() res: Response,
    @Query('format') format?: string,
    @Query('limit') limit?: string,
  ) {
    const take = Math.min(5000, Number(limit) || 1000);
    const rows = await this.audit.recent(take);
    const fmt = (format || 'json').toLowerCase();
    if (fmt === 'csv') {
      const header = ['id', 'action', 'actor', 'targetType', 'targetId', 'ip', 'createdAt', 'meta'];
      const lines = [header.join(',')];
      for (const r of rows) {
        const cells = [
          r.id,
          r.action,
          r.actor || '',
          r.targetType || '',
          r.targetId || '',
          r.ip || '',
          r.createdAt.toISOString(),
          JSON.stringify(r.meta || {}).replace(/"/g, '""'),
        ];
        lines.push(cells.map((c) => `"${String(c)}"`).join(','));
      }
      res.setHeader('Content-Type', 'text/csv; charset=utf-8');
      res.setHeader('Content-Disposition', 'attachment; filename="yanqi-audits.csv"');
      return res.send('\uFEFF' + lines.join('\n'));
    }
    res.setHeader('Content-Type', 'application/json; charset=utf-8');
    res.setHeader('Content-Disposition', 'attachment; filename="yanqi-audits.json"');
    return res.send(JSON.stringify({ exportedAt: new Date().toISOString(), count: rows.length, items: rows }, null, 2));
  }


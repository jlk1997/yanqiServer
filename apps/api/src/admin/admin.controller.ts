  @Get('health/ready')
  async ready() {
    let dbOk = false;
    let err: string | null = null;
    try {
      await this.prisma.$queryRaw`SELECT 1`;
      dbOk = true;
    } catch (e: any) {
      err = String(e?.message || e).slice(0, 200);
    }
    const body = {
      ok: dbOk,
      probe: 'ready',
      db: dbOk ? 'up' : 'down',
      error: err,
      time: new Date().toISOString(),
    };
    if (!dbOk) {
      throw new ServiceUnavailableException(body);
    }
    return body;
  }

